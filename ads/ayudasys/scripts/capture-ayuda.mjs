import { chromium } from 'playwright';
import { mkdirSync, writeFileSync } from 'node:fs';
const base = 'http://localhost:3010';
mkdirSync('public/shots', {recursive:true});
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
const page=await browser.newPage({viewport:{width:1360,height:900},deviceScaleFactor:1});
const shot=async name=>{await page.waitForTimeout(500);await page.screenshot({path:`public/shots/${name}.png`});};
try {
 await page.goto(base+'/login');
 await page.getByLabel('Email address').fill('admin@example.com');
 await page.getByLabel('Password',{exact:true}).fill('password');
 await page.getByRole('button',{name:'Sign in to workspace'}).click();
 await page.waitForURL('**/dashboard');
 await page.goto(base+'/programs');
 await page.getByRole('button',{name:'Create program',exact:true}).click();
 await page.getByLabel('Program name').fill('Pamamahagi ng Pagkain - Demo');
 await page.getByLabel('Assistance per household').fill('5 kg bigas at food pack');
 await page.getByLabel('Distribution date').fill('2026-11-07');
 await page.getByLabel('Distribution venue').fill('Barangay Malinaw - Demo');
 await page.locator('form').getByRole('button',{name:'Create program',exact:true}).click();
 await page.getByRole('heading',{name:'Pamamahagi ng Pagkain - Demo'}).waitFor();
 await page.goto(base+'/households/create');
 await page.getByLabel('Head of family').fill('Mila Reyes (Demo)');
 await page.getByLabel('Purok / Sitio').fill('Purok 2');
 await page.getByLabel('Complete address').fill('12 Sampaguita, Barangay Malinaw (Demo)');
 await page.getByLabel('Latitude',{exact:true}).fill('14.6760');
 await page.getByLabel('Longitude',{exact:true}).fill('121.0437');
 await shot('register');
 await page.getByRole('button',{name:'Save household'}).click();
 await page.waitForURL('**/households/1');
 await page.getByLabel('Select assistance program').selectOption('1');
 await page.getByRole('button',{name:'Enroll & issue stub'}).click();
 await page.locator('.qr-stub img').waitFor();
 await page.waitForFunction(()=>document.querySelector('.qr-stub img')?.src.startsWith('data:image/png'));
 const token=(await page.locator('.stub-token').textContent()).trim();
 await page.locator('.qr-stub').screenshot({path:'public/shots/stub.png'});
 await page.goto(base+'/distribute');
 await page.getByLabel('QR stub code').fill(token);
 await page.getByRole('button',{name:'Find household'}).click();
 await page.getByText('Registered for this program',{exact:true}).waitFor();
 await shot('verify');
 await page.getByRole('checkbox').check();
 await shot('confirm');
 await page.getByRole('button',{name:'Confirm & release assistance'}).click();
 await page.getByText('Already claimed',{exact:true}).waitFor();
 await shot('released');
 await page.goto(base+'/dashboard');
 await page.getByRole('heading',{name:'Community overview'}).waitFor();
 await shot('dashboard');
 writeFileSync('public/shots/provenance.json',JSON.stringify({source:'Local AyudaSys UI',database:'storage/ad-demo.db',fictional:true,lookup:'Actual stub-code lookup, no physical camera scan',release:'Confirmed through UI',screens:['register','stub','verify','confirm','released','dashboard']},null,2));
 console.log('Captured real registration, QR stub, lookup, confirmation, release and dashboard.');
} finally {await browser.close()}
